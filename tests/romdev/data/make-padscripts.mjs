#!/usr/bin/env node
// make-padscripts.mjs: write the movement scripts (lib/movement.mjs) as pad
// script files the engine's `padscript` command plays (client/cl_testscript.c).
// Both builds play the same files, so native and wasm get identical input.
//
//   node tests/romdev/data/make-padscripts.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SCRIPTS } from '../lib/movement.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const BUTTONS = { south: 0, east: 1, west: 2, north: 3, a: 0, b: 1, x: 2, y: 3, select: 4, start: 6, l3: 7, r3: 8, l: 9, r: 10, up: 11, down: 12, left: 13, right: 14 };
const stick = (v) => Math.max(-32768, Math.min(32767, Math.round((v || 0) * 32767)));
const trig = (v) => Math.max(0, Math.min(32767, Math.round((v || 0) * 32767)));

for (const [name, steps] of Object.entries(SCRIPTS)) {
  const lines = [`# ${name}: generated by make-padscripts.mjs from lib/movement.mjs`,
    '# frames lx ly rx ry lt rt [buttons]'];
  for (const { frames, pad } of steps) {
    const a = pad.axes || {};
    const buttons = Object.keys(pad).filter((k) => k !== 'axes' && pad[k]).map((k) => BUTTONS[k]);
    lines.push([frames, stick(a.lx), stick(a.ly), stick(a.rx), stick(a.ry), trig(a.lt), trig(a.rt), ...buttons].join(' '));
  }
  fs.writeFileSync(path.join(here, 'padscripts', `${name}.pad`), lines.join('\n') + '\n');
  console.log(`${name}.pad: ${steps.length} steps`);
}
